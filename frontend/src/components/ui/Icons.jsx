export function getCategoryIcon(category = "", size = 16) {
  const cat = String(category).toLowerCase();
  if (cat.includes("compute") || cat.includes("instance") || cat.includes("vm")) {
    return <ServerRackIcon size={size} />;
  }
  if (cat.includes("serverless") || cat.includes("lambda") || cat.includes("function")) {
    return <ServerRackIcon size={size} />;
  }
  if (cat.includes("storage") || cat.includes("s3") || cat.includes("bucket")) {
    return <StorageIcon size={size} />;
  }
  if (cat.includes("network") || cat.includes("vpc") || cat.includes("subnet") || cat.includes("router")) {
    return <NetworkIcon size={size} />;
  }
  if (cat.includes("database") || cat.includes("redshift") || cat.includes("sql")) {
    return <DatabaseIcon size={size} />;
  }
  if (cat.includes("security") || cat.includes("firewall") || cat.includes("iam")) {
    return <SecurityIcon size={size} />;
  }
  if (cat.includes("analytics") || cat.includes("monitoring")) {
    return <AnalyticsIcon size={size} />;
  }
  return <PackageIcon size={size} />;
}

export function getResourceBadgeIcon(resourceOrType = "", size = 16, color = "#FFFFFF") {
  const str = (
    typeof resourceOrType === "string"
      ? resourceOrType
      : (
          resourceOrType?.resourceType ||
          resourceOrType?.category ||
          resourceOrType?.id ||
          resourceOrType?.schema?.terraformType ||
          resourceOrType?.terraformType ||
          ""
        )
  ).toLowerCase();

  if (str.includes("ec2") || str.includes("vm") || str.includes("instance") || str.includes("compute")) {
    return <CpuChipIcon size={size} color={color} />;
  }
  if (str.includes("lambda") || str.includes("serverless") || str.includes("function") || str.includes("queue") || str.includes("sns") || str.includes("topic") || str.includes("event") || str.includes("api")) {
    return <ServerlessIcon size={size} color={color} />;
  }
  if (str.includes("s3") || str.includes("storage") || str.includes("bucket")) {
    return <StorageIcon size={size} color={color} />;
  }
  if (str.includes("db") || str.includes("rds") || str.includes("dynamo") || str.includes("database") || str.includes("redis") || str.includes("elasticache") || str.includes("bigquery")) {
    return <DatabaseIcon size={size} color={color} />;
  }
  if (str.includes("vpc") || str.includes("subnet") || str.includes("network") || str.includes("lb") || str.includes("gateway") || str.includes("route") || str.includes("dns") || str.includes("cloudfront") || str.includes("eip") || str.includes("address")) {
    return <NetworkIcon size={size} color={color} />;
  }
  if (str.includes("kms") || str.includes("key")) {
    return <LockIcon size={size} color={color} />;
  }
  if (str.includes("alarm") || str.includes("alert")) {
    return <AlertIcon size={size} color={color} />;
  }
  if (str.includes("iam") || str.includes("security") || str.includes("secret") || str.includes("firewall") || str.includes("trail") || str.includes("budget") || str.includes("log")) {
    return <SecurityIcon size={size} color={color} />;
  }
  if (str.includes("analytics") || str.includes("redshift")) {
    return <AnalyticsIcon size={size} color={color} />;
  }
  return <PackageIcon size={size} color={color} />;
}

